// Turns the CSS cures that inpage.js collected (font size, line height, text colour, tap-target size) into three stylesheets:
//   src/styles/ux-auto.css         laptop pages
//   src/styles/ux-auto-phone.css   pages a phone gets from the laptop site (inside @media (max-width: 767px))
//   src/app/(m)/ux-auto.css        the phone app pages (/m)
// and writes .task-log/ux-audit/MANUAL.md: the problems that need a hand (no class to aim at, tiny dots, no colour that passes).
//   node tools/ux-audit/fixgen.mjs --from=.task-log/ux-before2[,.task-log/ux-after1]     (several audits are merged: the strongest cure wins)
// Run the audit again after a build with these files in: what is left over is generated into the same files (cumulative), so it converges.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const from = (process.argv.find((a) => a.startsWith("--from=")) ?? "--from=.task-log/ux-audit").slice(7).split(",");
const FILES = {
  laptop: "src/styles/ux-auto.css",
  phoneSite: "src/styles/ux-auto-phone.css",
  app: "src/app/(m)/ux-auto.css",
};
const APP = /\.(ma|mp|lnc|m)-[a-z0-9]/; // classes of the phone app (src/app/(m), components/site/mobile)

// Tailwind helper classes (and anything that would hit every element of a kind) are no good as an address; headings keep their own tight line height
const WIDE = /.(inline-flex|inline-block|inline|block|flex|grid|hidden|absolute|relative|fixed|sticky|transition|btn)(.|s|>|$)/;
const lastTag = (sel) => (sel.split(">").pop().trim().match(/^[a-z0-9]+/) ?? [""])[0];
const merged = { laptop: new Map(), phoneSite: new Map(), app: new Map() };
const manual = new Map();
const num = (v) => parseFloat(v);
let rows = 0;
for (const dir of from) {
  const p = join(dir, "raw.jsonl");
  if (!existsSync(p)) continue;
  for (const line of readFileSync(p, "utf8").split("\n").filter(Boolean)) {
    const row = JSON.parse(line);
    rows++;
    for (const m of row.manual ?? []) {
      const k = `${m.r} | ${row.device} | ${m.el} | ${m.c}`;
      const e = manual.get(k) ?? { pages: new Set(), r: m.r, device: row.device, el: m.el, c: m.c };
      e.pages.add(row.path);
      manual.set(k, e);
    }
    for (const f of row.fixes ?? []) {
      if (WIDE.test(f.s) || (f.r === "UI13" && !["p", "li", "small", "dd", "figcaption"].includes(lastTag(f.s)))) {
        const k = `${f.r} | ${row.device} | ${f.s} | skipped: too wide a selector or a heading (${f.c})`;
        const e = manual.get(k) ?? { pages: new Set(), r: f.r, device: row.device, el: f.s, c: f.c + " (not generated: selector too wide / heading)" };
        e.pages.add(row.path);
        manual.set(k, e);
        continue;
      }
      const target = APP.test(f.s) ? "app" : row.device === "phone" ? "phoneSite" : "laptop";
      const sel = merged[target];
      if (f.r === "UX02" && !f.p) continue; // the old cure (a bigger min-height changed how switches and tabs look) was replaced by an invisible hit area
      const rule = sel.get(f.s) ?? { props: {} };
      if (f.p) {
        const q = ((rule.pseudo ??= {})[f.p.ps] ??= { dx: 0, dy: 0 });
        q.dx = Math.max(q.dx, f.p.dx);
        q.dy = Math.max(q.dy, f.p.dy);
        if (f.p.rel) rule.props.position = { value: "relative", demand: 1 };
      }
      for (const decl of f.c.split(";").filter(Boolean)) {
        const i = decl.indexOf(":"), prop = decl.slice(0, i), value = decl.slice(i + 1);
        const old = rule.props[prop];
        const numeric = ["font-size", "line-height", "min-height", "min-width"].includes(prop);
        // the strongest cure wins: the biggest number, or the colour that moved the most
        if (!old || (numeric ? num(value) > num(old.value) : (f.m ?? 0) > old.demand)) rule.props[prop] = { value, demand: f.m ?? 0 };
      }
      sel.set(f.s, rule);
    }
  }
}

const css = (map) =>
  [...map.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([s, r]) => [
      ...(Object.keys(r.props).length ? [`html ${s} { ${Object.entries(r.props).map(([p, v]) => `${p}: ${v.value}`).join("; ")}; }`] : []),
      // tap target: an invisible box around the element, the element itself looks exactly as before
      ...Object.entries(r.pseudo ?? {}).map(([ps, q]) => `html ${s}${ps} { content: ""; position: absolute; inset: -${q.dy}px -${q.dx}px; }`),
    ]);
const head = (what) => `/* AUTO-GENERATED by tools/ux-audit/fixgen.mjs from the UX audit (${what}). Do not edit by hand: run the audit again and node tools/ux-audit/fixgen.mjs.\n   "html" in front of every selector makes it win over the component stylesheets that load later. Rules: body text >= 16px (phone 15px), labels >= 14px (phone 12px),\n   contrast 4.5:1 (hue kept, only lightness moves), tap target >= 24px (phone 44px). */\n`;
for (const [k, file] of Object.entries(FILES)) {
  const lines = css(merged[k]);
  let body = head(k === "laptop" ? "laptop pages" : k === "app" ? "phone app pages" : "laptop-site pages opened on a phone") + (k === "phoneSite" ? "@media (max-width: 767px) {\n" + lines.map((l) => "  " + l).join("\n") + "\n}\n" : lines.join("\n") + "\n");
  if (!lines.length) body = head(k) + "/* nothing to fix */\n";
  writeFileSync(file, body);
  console.log(`${file}: ${lines.length} rules`);
}
const byRule = {};
for (const e of manual.values()) (byRule[e.r] ??= []).push(e);
let md = `# Needs a hand (the generator could not aim a CSS rule at these)\n\n${manual.size} items.\n`;
for (const [r, l] of Object.entries(byRule)) md += `\n## ${r} (${l.length})\n` + l.map((e) => `- ${e.device} ${e.el} — ${e.c} — ${[...e.pages].slice(0, 3).join(", ")}${e.pages.size > 3 ? ` +${e.pages.size - 3} pages` : ""}`).join("\n") + "\n";
writeFileSync(join(from[from.length - 1], "MANUAL.md"), md);
console.log(`${manual.size} manual items → ${join(from[from.length - 1], "MANUAL.md")}  (${rows} audit rows read)`);
