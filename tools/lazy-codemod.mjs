// LAZY CODEMOD: makes the heavy client components load only on the pages that really render them.
//   node tools/lazy-codemod.mjs plan [minKB]     list what would change (default: client trees of 10 KB source or more)
//   node tools/lazy-codemod.mjs apply [minKB]    rewrite the SERVER files' imports and write src/components/site/lazy.tsx
// Why: Next sends to a page the JS of every client file that its server code can reach, even if the page never shows it. A client
// file that is imported only through next/dynamic INSIDE a client file ("lazy.tsx") is its own chunk, loaded when rendered (still
// server-rendered, so the HTML and SEO stay the same). The codemod only rewrites imports of components that are used as <Name .../>
// in a server file; anything else (functions, constants, default exports) is reported and left alone.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";

const mode = process.argv[2] ?? "plan";
const minKB = Number(process.argv[3] ?? 10);
const LAZY = "src/components/site/lazy.tsx";
const files = [];
(function walk(d) { for (const n of readdirSync(d)) { const f = join(d, n); if (statSync(f).isDirectory()) walk(f); else if (/\.tsx?$/.test(n)) files.push(f.split("\\").join("/")); } })("src");
const info = {};
for (const f of files) { const t = readFileSync(f, "utf8"); info[f] = { t, client: /^\s*["']use client["']/m.test(t.slice(0, 300)), size: t.length }; }
const resolve = (from, spec) => {
  let base;
  if (spec.startsWith("@/")) base = "src/" + spec.slice(2);
  else if (spec.startsWith(".")) base = posix.join(posix.dirname(from), spec);
  else return null;
  for (const e of ["", ".tsx", ".ts", "/index.tsx", "/index.ts"]) if (info[base + e]) return base + e;
  return null;
};
// static value imports of a file: [{ names:[{name,local}], spec, file, line }]
const IMPORT = /import\s+(type\s+)?\{([^}]*)\}\s+from\s+["']([^"']+)["'];?[ \t]*\r?\n?/g;
const importsOf = (f) => [...info[f].t.matchAll(IMPORT)].filter((m) => !m[1]).map((m) => ({ text: m[0], spec: m[3], file: resolve(f, m[3]), names: m[2].split(",").map((s) => s.trim()).filter(Boolean).map((s) => { const parts = s.split(/\s+as\s+/); return { name: parts[0].replace(/^type\s+/, ""), local: (parts[1] ?? parts[0]).replace(/^type\s+/, ""), isType: /^type\s/.test(s) }; }) }));
const staticDeps = (f) => [...info[f].t.matchAll(/(?:import|export)[^"';]*?from\s+["']([^"']+)["']|import\s+["']([^"']+)["']/g)].map((m) => resolve(f, m[1] ?? m[2])).filter(Boolean);
const weightMemo = new Map();
const treeWeight = (f) => { // source size of this client file + the client files it pulls in through static imports
  if (weightMemo.has(f)) return weightMemo.get(f);
  const seen = new Set(); const stack = [f]; let w = 0;
  while (stack.length) { const x = stack.pop(); if (seen.has(x)) continue; seen.add(x); if (!info[x].client && x !== f) continue; w += info[x].size; stack.push(...staticDeps(x)); }
  weightMemo.set(f, w); return w;
};

const edits = []; // { server, importText, wrap:[{name,local,file,spec}], keep:[names] }
const skipped = [];
for (const f of files) {
  if (info[f].client || f === LAZY || f.includes("/admin/") || f === "src/app/(site)/layout.tsx" /* shown on every page: nothing to save */ || /\.d\.ts$/.test(f)) continue;
  for (const imp of importsOf(f)) {
    if (!imp.file || !info[imp.file].client || treeWeight(imp.file) < minKB * 1000) continue;
    const wrap = [], keep = [];
    for (const n of imp.names) {
      if (n.isType) { keep.push(n); continue; }
      // used as <Name .../> or as an entry of a map:  key: Name,
      const used = new RegExp(`<${n.local}[\\s>/]|[:=]\\s*${n.local}\\s*[,;)}]`).test(info[f].t);
      const exportedAsFn = new RegExp(`export\\s+(?:async\\s+)?(?:function|const)\\s+${n.name}\\b`).test(info[imp.file].t);
      if (used && /^[A-Z]/.test(n.name) && exportedAsFn) wrap.push({ ...n, file: imp.file }); else { keep.push(n); skipped.push(`${f}: ${n.name} from ${imp.spec} (not a component used as JSX)`); }
    }
    if (wrap.length) edits.push({ server: f, imp, wrap, keep });
  }
}
// lazy.tsx
const lazyNames = new Map(); // name -> file
const clash = [];
for (const e of edits) for (const w of e.wrap) { if (lazyNames.has(w.name) && lazyNames.get(w.name) !== w.file) clash.push(w.name); lazyNames.set(w.name, w.file); }
const rel = (file) => "./" + posix.relative(posix.dirname(LAZY), file).replace(/\.tsx?$/, "");
const lazySrc = `"use client";

import dynamic from "next/dynamic";

// GENERATED by tools/lazy-codemod.mjs (re-run it after adding a big client component). Each line is its own chunk: a page downloads
// the code of the components it renders, not of all of them. They are still rendered on the server, so the HTML and SEO are the same.
` + [...lazyNames].sort().map(([name, file]) => `export const ${name} = dynamic(() => import("${rel(file)}").then((m) => m.${name}));`).join("\n") + "\n";

console.log(`${edits.length} server imports to rewrite, ${lazyNames.size} lazy components, threshold ${minKB} KB source`);
for (const e of edits) console.log(`  ${e.server.replace("src/", "")}: ${e.wrap.map((w) => w.name).join(", ")}${e.keep.length ? "   (kept: " + e.keep.map((k) => k.name).join(", ") + ")" : ""}`);
if (clash.length) { console.log("NAME CLASH, stop:", clash.join(", ")); process.exit(1); }
if (skipped.length) { console.log("\nleft alone:"); for (const s of skipped) console.log("  " + s); }
if (mode === "apply") {
  for (const e of edits) {
    const depth = posix.relative(posix.dirname(e.server), posix.dirname(LAZY)) || ".";
    const lazyRel = (depth === "." ? "./lazy" : depth + "/lazy");
    const names = e.wrap.map((w) => (w.local !== w.name ? `${w.name} as ${w.local}` : w.name)).join(", ");
    const keepLine = e.keep.length ? `import { ${e.keep.map((k) => (k.isType ? "type " : "") + (k.local !== k.name ? `${k.name} as ${k.local}` : k.name)).join(", ")} } from "${e.imp.spec}";\n` : "";
    info[e.server].t = info[e.server].t.replace(e.imp.text, keepLine + `import { ${names} } from "${lazyRel}";\n`);
  }
  for (const e of edits) writeFileSync(e.server, info[e.server].t);
  writeFileSync(LAZY, lazySrc);
  console.log("\nwritten. Now run: npx tsc --noEmit && npx eslint src");
}
